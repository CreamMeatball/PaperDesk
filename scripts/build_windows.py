#!/usr/bin/env python3
"""Build the Windows app folder and per-user installer (Inno Setup).

Run on Windows x64 with requirements/windows-build.lock installed and a runtime from
scripts/build_analysis_runtime.py. Produces <out>/Paperdesk-<version>-<build>-x64-setup.exe
and a JSON receipt. The app has two executables: Paperdesk.exe (window) and
paperdesk-cli.exe (console, for MCP and other CLI commands).

Only --development builds exist for now: unsigned and without an updater. Release builds
will add Authenticode signing and WinSparkle updates.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
import platform
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from paperdesk import APP_NAME, __version__  # noqa: E402

BUILD_LOCK = ROOT / "requirements/windows-build.lock"
RUNTIME_LOCK = ROOT / "requirements/docling-windows.lock"
CLI_NAME = "paperdesk-cli"
REPOSITORY_URL = "https://github.com/HojooonKim/paperdesk"
# The macOS icon artwork (packaging/macos/Paperdesk.icon) cropped to the tile, 16-256 px; also used by install_source.py.
ICON = ROOT / "packaging/windows/Paperdesk.ico"

SPEC = """# Generated by scripts/build_windows.py
a = Analysis([{launcher!r}], pathex=[{src!r}],
             datas=[({static!r}, 'paperdesk/web/static'), ({worker!r}, 'paperdesk/infrastructure')],
             hiddenimports=['webview.platforms.winforms', 'webview.platforms.edgechromium'],
             excludes=['tests', 'experiments', 'PyQt5', 'PyQt6', 'PySide6', 'tkinter'])
pyz = PYZ(a.pure)
window = EXE(pyz, a.scripts, [], exclude_binaries=True, name={app!r}, console=False,
             icon={icon!r}, version={app_version!r})
console = EXE(pyz, a.scripts, [], exclude_binaries=True, name={cli!r}, console=True,
              icon={icon!r}, version={cli_version!r})
COLLECT(window, console, a.binaries, a.datas, name={app!r})
"""


def run(*args) -> None:
    subprocess.run([str(arg) for arg in args], check=True, cwd=ROOT)


def pins(lock: Path) -> dict[str, str]:
    return dict(line.strip().split("==", 1) for line in lock.read_text(encoding="utf-8").splitlines()
                if line.strip() and not line.startswith("#"))


def dependency_issues() -> list[str]:
    issues = []
    for name, version in pins(BUILD_LOCK).items():
        try:
            installed = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            installed = None
        if installed != version:
            issues.append(f"{name}=={version} (installed: {installed or 'missing'})")
    return issues


def find_iscc() -> Path | None:
    candidates = [os.environ.get("ISCC", ""), shutil.which("ISCC") or "",
                  os.path.expandvars(r"%LOCALAPPDATA%\Programs\Inno Setup 6\ISCC.exe"),
                  os.path.expandvars(r"%ProgramFiles(x86)%\Inno Setup 6\ISCC.exe"),
                  os.path.expandvars(r"%ProgramFiles%\Inno Setup 6\ISCC.exe")]
    return next((Path(c) for c in candidates if c and Path(c).is_file()), None)


def verify_production_modules(executable: Path) -> None:
    """Reject accidental inclusion of development fixtures or unfinished integrations."""
    from PyInstaller.archive.readers import CArchiveReader

    archive = CArchiveReader(str(executable)).open_embedded_archive("PYZ.pyz")
    blocked = {"paperdesk.providers.demo", "paperdesk.providers.chatgpt_plan"}
    unexpected = sorted(name for name in archive.toc
                        if name.split(".")[0] in {"tests", "experiments"} or name in blocked)
    if unexpected:
        raise ValueError("Development modules in app: " + ", ".join(unexpected))


def file_version(build: int) -> tuple[int, int, int, int]:
    numbers = [int(n) for n in re.findall(r"\d+", __version__)[:3]]
    return (*numbers, *[0] * (3 - len(numbers)), build)


def version_resource(path: Path, *, build: int, filename: str, description: str) -> None:
    """Product name and version in the executable; signing services check these."""
    numbers = file_version(build)
    text = ".".join(map(str, numbers))
    path.write_text(f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers={numbers}, prodvers={numbers}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Paperdesk contributors'),
      StringStruct('FileDescription', {description!r}),
      StringStruct('FileVersion', {text!r}),
      StringStruct('InternalName', {filename!r}),
      StringStruct('LegalCopyright', 'Copyright 2026 Paperdesk contributors'),
      StringStruct('OriginalFilename', {filename!r}),
      StringStruct('ProductName', {APP_NAME!r}),
      StringStruct('ProductVersion', {__version__!r})])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""", encoding="utf-8")


def source_tree_sha256() -> str:
    """Same definition as the macOS build, so both receipts identify the same source tree."""
    digest = hashlib.sha256()
    sources = [p for folder in ('src', 'scripts', 'packaging', 'requirements') for p in (ROOT / folder).rglob('*')
               if p.is_file() and '__pycache__' not in p.parts]
    sources += [ROOT / 'pyproject.toml', ROOT / 'THIRD_PARTY_NOTICES.md']
    sources += [ROOT / name for name in ('LICENSE', 'NOTICE') if (ROOT / name).is_file()]
    for source in sorted(sources):
        digest.update(str(source.relative_to(ROOT).as_posix()).encode() + b'\0' + source.read_bytes())
    return digest.hexdigest()


def copy_licenses(app: Path, dependencies: dict[str, str]) -> None:
    for name in ('LICENSE', 'NOTICE', 'THIRD_PARTY_NOTICES.md', 'docs/privacy.md', 'docs/support.md'):
        if (ROOT / name).is_file():
            shutil.copy2(ROOT / name, app / Path(name).name)
    licenses = app / 'licenses'
    licenses.mkdir(exist_ok=True)
    python_license = Path(sys.base_prefix) / 'LICENSE.txt'
    if not python_license.is_file():
        raise SystemExit('The Python distribution LICENSE.txt is required for bundling')
    shutil.copy2(python_license, licenses / 'CPython-LICENSE.txt')
    for dependency in dependencies:
        distribution = importlib.metadata.distribution(dependency)
        for entry in distribution.files or ():
            name = str(entry)
            if '.dist-info/' in name and ('/licenses/' in name or entry.name.upper().startswith(('LICENSE', 'COPYING'))):
                source = Path(distribution.locate_file(entry))
                if source.is_file():
                    destination = licenses / dependency / name.split('.dist-info/', 1)[1]
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(source, destination)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build-number", required=True, type=int)
    parser.add_argument("--analysis-runtime", type=Path, required=True, help="Portable runtime from scripts/build_analysis_runtime.py")
    parser.add_argument("--development", action="store_true", help="Unsigned build without updates (the only kind for now)")
    parser.add_argument("--work", type=Path, default=ROOT / "build/windows", help="Scratch folder (a local disk is much faster)")
    parser.add_argument("--out", type=Path, default=ROOT / "dist/windows")
    args = parser.parse_args()
    if sys.platform != "win32" or platform.machine().lower() not in ("amd64", "x86_64"):
        parser.error("Build the Windows app on Windows x64")
    if not args.development:
        parser.error("Release builds need Authenticode signing and WinSparkle, which are not set up yet; use --development")
    if args.build_number < 1:
        parser.error("Build number must be a positive integer and must increase for every release")
    runtime = args.analysis_runtime.resolve()
    if not (runtime / "python.exe").is_file() or not (runtime / "paperdesk-analysis.json").is_file():
        parser.error("Build the portable Docling runtime first (scripts/build_analysis_runtime.py)")
    runtime_manifest = json.loads((runtime / "paperdesk-analysis.json").read_text(encoding="utf-8"))
    if runtime_manifest.get("lock_sha256") != hashlib.sha256(RUNTIME_LOCK.read_bytes()).hexdigest():
        parser.error("The Docling runtime does not match requirements/docling-windows.lock")
    issues = dependency_issues()
    if issues:
        parser.error("Install requirements/windows-build.lock first: " + "; ".join(issues))
    iscc = find_iscc()
    if not iscc:
        parser.error("Inno Setup 6 (ISCC.exe) not found; install it or set ISCC")

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    stem = f"{APP_NAME}-{__version__}-{args.build_number}-x64"
    installer = out / (stem + "-setup.exe")
    if installer.exists():
        parser.error(f"Refusing to overwrite a release artifact: {installer}")
    work = args.work.resolve() / stem
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)

    icon = ICON
    version_resource(work / "app-version.txt", build=args.build_number, filename=APP_NAME + ".exe", description=APP_NAME)
    version_resource(work / "cli-version.txt", build=args.build_number, filename=CLI_NAME + ".exe",
                     description=APP_NAME + " command line (MCP, doctor, backup)")
    spec = work / (APP_NAME + ".spec")
    spec.write_text(SPEC.format(
        launcher=str(ROOT / "packaging/windows/launcher.py"), src=str(ROOT / "src"),
        static=str(ROOT / "src/paperdesk/web/static"), worker=str(ROOT / "src/paperdesk/infrastructure/docling_worker.py"),
        app=APP_NAME, cli=CLI_NAME, icon=str(icon),
        app_version=str(work / "app-version.txt"), cli_version=str(work / "cli-version.txt")), encoding="utf-8")
    run(sys.executable, "-m", "PyInstaller", "--noconfirm", "--workpath", work / "freeze", "--distpath", work / "dist", spec)
    app = work / "dist" / APP_NAME
    for name in (APP_NAME, CLI_NAME):
        verify_production_modules(app / (name + ".exe"))

    shutil.copytree(runtime, app / "analysis-runtime")
    dependencies = {name: importlib.metadata.version(name) for name in pins(BUILD_LOCK)}
    copy_licenses(app, dependencies)
    manifest = {'version': __version__, 'build': args.build_number, 'arch': 'x64',
                'python': platform.python_version(), 'dependencies': dependencies,
                'analysis_runtime': runtime_manifest, 'source_tree_sha256': source_tree_sha256(),
                'lock_sha256': hashlib.sha256(BUILD_LOCK.read_bytes()).hexdigest()}
    (app / 'build-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')

    run(iscc, "/Q", f"/DAppName={APP_NAME}", f"/DAppVersion={__version__}",
        "/DFileVersion=" + ".".join(map(str, file_version(args.build_number))), f"/DAppURL={REPOSITORY_URL}",
        f"/DSourceDir={app}", f"/DOutputDir={out}", f"/DOutputBaseFilename={installer.stem}", f"/DIconFile={icon}",
        ROOT / "packaging/windows/paperdesk.iss")
    digest = hashlib.sha256(installer.read_bytes()).hexdigest()
    # Used by the future release script to reject unsigned/development artifacts.
    receipt = {**manifest, "installer": installer.name, "sha256": digest, "updates": False, "signed": False}
    installer.with_suffix(".json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(installer)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
